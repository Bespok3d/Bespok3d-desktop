// Generate the component + hook inventory (doc/component-inventory.md) from the renderer source.
//   node scripts/component-inventory.mjs           write the inventory
//   node scripts/component-inventory.mjs --check     fail if the committed inventory is stale
//
// The inventory is the cheap half of "reuse before you create" (feedback_reuse_before_create +
// doc/codebase-fix/reuse-and-fakes-gate.md, Deliverable B): a true semantic-duplicate detector is
// research-grade, but most reinvention happens because the author never LOOKED. A generated list of
// every exported component/hook + its file + a one-line purpose makes the search free, so CLAUDE.md's
// coding procedure can say "step 0: read the inventory, reuse before you create". jscpd still gates the
// copy-paste; this makes the look-first habit trivial.
//
// parseExports is pure (text in, entries out) so it is unit-tested without the filesystem; the walk +
// write + --check IO runs only when this script is invoked directly. Components are `export function`
// by the coding rules (no `const X = () =>` for named functions), so that one shape is exhaustive.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const REPO_ROOT = fileURLToPath(new URL('..', import.meta.url))
const RENDERER_SRC = join(REPO_ROOT, 'src/renderer/src')
const INVENTORY_REL = 'doc/component-inventory.md'

const EXPORT_FN = /^export\s+(?:default\s+)?(?:async\s+)?function\s+([A-Za-z_$][\w$]*)/
const isComponentName = (name) => /^[A-Z]/.test(name) && /[a-z]/.test(name)
const isHookName = (name) => /^use[A-Z]/.test(name)

// The one-line purpose is the LEAD line of the `//` comment block immediately above the export
// (skipping blank lines). Taking the block's first line keeps it the topic sentence rather than a
// trailing fragment of a multi-line comment. Most components have none yet; an author adds one as
// they touch a file, which also helps readers.
const COMMENT_LINE = /^\s*\/\//
function purposeAbove(lines, exportIndex) {
  let bottom = exportIndex - 1
  while (bottom >= 0 && lines[bottom].trim() === '') bottom--
  if (bottom < 0 || !COMMENT_LINE.test(lines[bottom])) return ''
  let top = bottom
  while (top - 1 >= 0 && COMMENT_LINE.test(lines[top - 1])) top--
  const lead = lines[top].match(/^\s*\/\/\s?(.*)$/)
  return lead ? lead[1].trim() : ''
}

export function parseExports(text) {
  const lines = text.split('\n')
  const entries = []
  lines.forEach((line, index) => {
    const match = EXPORT_FN.exec(line)
    if (!match) return
    const name = match[1]
    const kind = isHookName(name) ? 'hook' : isComponentName(name) ? 'component' : null
    if (!kind) return
    entries.push({ name, kind, purpose: purposeAbove(lines, index) })
  })
  return entries
}

// The area groups the renderer tree into the places an author actually searches: the design system,
// the shared primitives, the hooks, and one bucket per feature.
function areaOf(relPath) {
  if (relPath.startsWith('design-system/')) return 'Design system'
  if (relPath.startsWith('components/common/')) return 'Common primitives'
  if (relPath.startsWith('hooks/')) return 'Hooks'
  const feature = relPath.match(/^components\/([^/]+)\//)
  if (feature) return `Feature: ${feature[1]}`
  const top = relPath.split('/')[0]
  return `Other: ${top}`
}

function groupByArea(files) {
  const rows = files.flatMap(({ path, entries }) => entries.map((entry) => ({ ...entry, path, area: areaOf(path) })))
  const byArea = new Map()
  for (const row of rows) {
    if (!byArea.has(row.area)) byArea.set(row.area, [])
    byArea.get(row.area).push(row)
  }
  return byArea
}

function renderRow(row) {
  const purpose = row.purpose ? ` - ${row.purpose}` : ''
  return `- \`${row.name}\` (${row.kind}) - [${row.path}](../src/renderer/src/${row.path})${purpose}`
}

function renderArea(area, rows) {
  const body = [...rows].sort((first, second) => first.name.localeCompare(second.name)).map(renderRow)
  return [`## ${area}`, '', ...body, ''].join('\n')
}

export function buildInventory(files) {
  const byArea = groupByArea(files)
  const total = files.reduce((sum, file) => sum + file.entries.length, 0)
  const head = [
    '# Component + hook inventory',
    '',
    '> GENERATED by `scripts/component-inventory.mjs` - do not edit by hand. Run `npm run inventory`',
    '> (from the repo root) to refresh; `scripts/check.sh` fails if this file is stale.',
    '',
    'Step 0 of any UI work: search this list and REUSE what already exists before authoring a new',
    'component, hook, or primitive. Reinvention is a hard-rule violation (feedback_reuse_before_create).',
    "A blank purpose just means nobody has written a one-line `//` comment above that export yet; add one",
    'as you touch the file.',
    '',
    `${total} exported components + hooks across ${byArea.size} areas.`,
    '',
  ]
  const sections = [...byArea.keys()].sort().map((area) => renderArea(area, byArea.get(area)))
  return head.join('\n') + '\n' + sections.join('\n') + '\n'
}

function walk(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    if (['node_modules', 'out', 'dist', 'coverage', 'test'].includes(name)) continue
    const full = join(dir, name)
    if (statSync(full).isDirectory()) walk(full, acc)
    else acc.push(full)
  }
  return acc
}

function collectFiles() {
  const isSource = (path) =>
    (path.endsWith('.ts') || path.endsWith('.tsx')) && !path.includes('.test.') && !path.includes('.stories.')
  return walk(RENDERER_SRC)
    .filter(isSource)
    .map((path) => ({ path: relative(RENDERER_SRC, path), entries: parseExports(readFileSync(path, 'utf8')) }))
    .filter((file) => file.entries.length > 0)
    .sort((first, second) => first.path.localeCompare(second.path))
}

function run() {
  const markdown = buildInventory(collectFiles())
  const target = join(REPO_ROOT, INVENTORY_REL)
  if (process.argv.includes('--check')) {
    const current = readFileSync(target, 'utf8')
    if (current !== markdown) {
      console.error(`${INVENTORY_REL} is stale - run \`npm run inventory\` (from the repo root) and commit the result.`)
      process.exit(1)
    }
    console.log(`${INVENTORY_REL} is up to date.`)
    return
  }
  writeFileSync(target, markdown)
  console.log(`Wrote ${INVENTORY_REL}.`)
}

if (process.argv[1] && process.argv[1].endsWith('component-inventory.mjs')) run()
